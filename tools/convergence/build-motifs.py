# Builds signal-motifs.js: taxonomy + tags + the precomputed ECHOES target index (+ 192×120 echo thumbnails).
# usage: python3 tools/convergence/build-motifs.py   (run from the repo root)
import json, subprocess, sys, os, re, io
sys.path.insert(0, os.path.dirname(__file__)); from tags import TAXONOMY, LW, ATLAS
from PIL import Image
ROOT = '.'
def node(js): return json.loads(subprocess.check_output(['node', '-e', js]))
lw = node('global.window={};require("./long-watch-data.js");require("./long-watch-visuals.js");console.log(JSON.stringify({ev:window.LW_DATA.events,vis:window.LW_VISUALS}))')
html = open('index.html', encoding='utf-8').read()
def arr(name):
    i = html.index('const %s=' % name) + len(name) + 7; d = 0; j = i
    while True:
        c = html[j]
        if c == '[': d += 1
        elif c == ']':
            d -= 1
            if not d: break
        j += 1
    return json.loads(html[i:j + 1])
archive, additions = arr('archive'), arr('additions')
assert set(LW) == {e['id'] for e in lw['ev']}, 'LW tags must cover every entry'
assert set(ATLAS) == {r['id'] for r in archive}, 'Atlas tags must cover every sourced record'
tax = [{'id': a, 'label': b, 'short': c, 'w': w} for a, b, c, w in TAXONOMY]; ids = {t['id'] for t in tax}
for k, v in list(LW.items()) + list(ATLAS.items()): assert set(v) <= ids, (k, v)
core = open('tools/convergence/motifs-core.js', encoding='utf-8').read()
# NUFORC witness submissions: tagged by the same rules as Intel stories (their own words only)
nu = node('global.window={__PSMotifData:{taxonomy:%s,targets:[],rarity:{}}};eval(require("fs").readFileSync("tools/convergence/motifs-core.js","utf8"));const A=%s;console.log(JSON.stringify(Object.fromEntries(A.map(r=>[r.id,window.PSMotifs.tag(r.title+" . "+(r.excerpt||""))]))))' % (json.dumps(tax), json.dumps(additions)))
def year_lbl(y): return f'{-y} BCE' if y < 0 else str(y)
os.makedirs('lw/thumb', exist_ok=True)
targets = []; lw_atlas = {e['atlas'] for e in lw['ev'] if e.get('atlas')}
for e in lw['ev']:
    if e['badge'] in ('hoax', 'modern') or not LW[e['id']]: continue  # hoaxes and modern reinterpretations are never offered as echoes
    v = lw['vis'][e['id']][0]; h = (v['hotspots'] or [{'x': .5, 'y': .5}])[0]
    im = Image.open(f"lw/img/{v['key']}-640.webp").convert('RGB'); W, H = im.size
    cw = min(W, H * 1.6); ch = cw / 1.6; cw *= .72; ch *= .72
    x0 = min(max(h['x'] * W - cw / 2, 0), W - cw); y0 = min(max(h['y'] * H - ch / 2, 0), H - ch)
    im.crop((round(x0), round(y0), round(x0 + cw), round(y0 + ch))).resize((192, 120), Image.LANCZOS).save(f"lw/thumb/{e['id']}.webp", 'WEBP', quality=72, method=6)
    targets.append({'k': 'lw:' + e['id'], 'y': e['year'], 'when': year_lbl(e['year']), 'place': e['place'], 'title': e['title'], 'tags': LW[e['id']], 'thumb': f"lw/thumb/{e['id']}.webp", 'real': v['real'], 'badge': e['badge']})
for r in archive:
    if r['id'] in lw_atlas or not ATLAS[r['id']]: continue
    if re.search(r'hoax|fabricat', r['summary'] + r['status'], re.I): continue
    m = re.match(r'(\d{4})', r['date']);
    if not m or 'present' in r['date']: continue
    targets.append({'k': 'at:' + r['id'], 'y': int(m.group(1)), 'when': m.group(1), 'place': r['place'], 'title': r['title'], 'tags': ATLAS[r['id']], 'thumb': (r.get('image') or {}).get('thumb'), 'real': bool(r.get('image')), 'badge': r['status']})
rar = {t['id']: sum(t['id'] in x['tags'] for x in targets) for t in tax}
data = {'taxonomy': tax, 'targets': targets, 'rarity': rar, 'lw': LW, 'atlas': ATLAS, 'nuforc': nu}
open('signal-motifs.js', 'w', encoding='utf-8').write('/* GENERATED by tools/convergence/build-motifs.py — edit tools/convergence/tags.py or motifs-core.js, then rebuild. */\nwindow.__PSMotifData=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n' + core)
# tag counts for the report
from collections import Counter
cnt = {s: Counter(t for v in src.values() for t in v) for s, src in (('lw', LW), ('atlas', ATLAS), ('nuforc', nu))}
json.dump({'counts': cnt, 'targets': len(targets), 'untagged': {'lw': [k for k, v in LW.items() if not v], 'atlas': [k for k, v in ATLAS.items() if not v], 'nuforc': sum(1 for v in nu.values() if not v)}}, open('/home/claude/motif-counts.json', 'w'), indent=1)
print(len(targets), 'targets;', os.path.getsize('signal-motifs.js'), 'bytes')
